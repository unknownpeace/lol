## 📋 Системные требования

* **ОС:** **OpenWrt 25.x+** (с пакетным менеджером `apk`) или **Alpine Linux 3.19 / 3.20 / 3.21+**.
* **Архитектура процессора:** `x86_64 (amd64)` или `aarch64 (arm64)`.
* **Оперативная память:** от **256 МБ** (рекомендуется 512 МБ и выше).
* **Для контейнеров Proxmox LXC (Alpine Linux):** в настройках контейнера или в `/etc/pve/lxc/<ID>.conf` должно быть разрешено устройство `/dev/net/tun` (в Proxmox 8+ включено по умолчанию для сетевых контейнеров, при необходимости скрипт сам создаст ноду `mknod /dev/net/tun c 10 200`).
