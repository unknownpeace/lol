## 🔥 Почему это решение не оставляет шансов конкурентам

* **Нативная поддержка Dual-OS (`OpenWrt 25.x+` и `Alpine Linux 3.x`):** единый чистый POSIX-скрипт одинаково безупречно работает как на роутерах/одноплатниках с OpenWrt (`procd` + `fw4`), так и в легковесных контейнерах **Proxmox LXC / VM на Alpine Linux** (`OpenRC` + нативный `nftables`).
* **3 независимых слота прокси (работают одновременно или по отдельности):**
  * **Слот 1 [Подписки HTTP/HTTPS]:** поддержка одной или нескольких подписок (Мульти-Саб), автоочистка несовместимых параметров (`fmt=xray/v2ray`) и фильтрация информационного мусора.
  * **Слот 2 [Личные ключи URI]:** прямая вставка ключей `vless://`, `hy2://`, `tuic://`, `ss://`, `trojan://`, `wg://`, `anytls://`, `mieru://`, `xhttp://` в локальный провайдер `my_nodes.yaml` с возможностью просмотра и поштучного удаления через меню.
  * **Слот 3 [Бесплатный Amnezia WARP 2.0]:** автоматическая регистрация аккаунта Cloudflare WARP (с обходом блокировки API через `--connect-to` и поддержкой ключей **WARP+**), живой сканер 4 лучших Anycast-узлов под вашего провайдера и **AWG 2.0 обфускация (`i1`) с мимикрией под бинарный DNS-запрос к `yabs.yandex.ru`**.
* **Режим «Белые списки / Анти-Шатдаун»:** в штатном режиме ноды РФ скрыты из подписки, чтобы автовыбор (`urltest`) не цеплялся за московский сервер с пингом 3 мс. При шатдаунах и фильтрации по «белым спискам» каскадные РФ-ноды из подписки включаются одной кнопкой в меню.
* **Никаких утечек DNS и IPv6 (Zero-Leak Architecture):**
  * **AdGuard Home** на порту `:53` режет рекламу, трекеры и `AAAA` (IPv6) запросы.
  * **Sing-Box Extended** на порту `:1053` отдает мгновенный **FakeIP (`198.18.0.0/15`)** для зарубежных и заблокированных ресурсов, а российские домены (`ru_domain`), торренты и NTP резолвит напрямую без задержек.
  * Блокировка DNS-запросов типа `HTTPS` (Type 65 / ECH) и `SVCB`, принудительный `reject` для DoT/DoQ (порт `853`) и подавление проблемного `UDP 443 (QUIC)` для YouTube/Google/AI.
* **Идеальная работа голоса в Discord, Telegram и WhatsApp:** выделенная маршрутизация UDP-портов `50000:50100`, STUN (`3478, 5349, 19302`) и актуальных списков голосовых серверов Discord (`discord-voice-ip-list.srs`).
* **Адаптивный тюнинг под железо (от 256 МБ до 8+ ГБ RAM):** скрипт сам считывает объем оперативной памяти и выставляет оптимальные лимиты `GOMEMLIMIT`, `GOGC=50`, размеры буферов ядра, `TCP BBR` и `nf_conntrack_max`, полностью исключая падения по OOM.
* **Транзакционная защита и Watchdog (Авто-Доктор):** перед любым изменением настроек создается слепок состояния. Если конфиг не проходит проверку или `singbox-tun` не поднимается — скрипт автоматически откатывает изменения. Встроенный Watchdog проверяет здоровье служб каждые 5 минут.

