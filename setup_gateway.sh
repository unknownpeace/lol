## 🛠 Возможности интерактивного меню (`gateway`)

При вводе команды `gateway` открывается панель управления с мгновенной загрузкой статуса:

1. **Статус служб, матрица пинга и тест на утечки (`Self-Test 2.0`):** проверка PID, потребления ОЗУ, статуса `singbox-tun`, `TCP BBR`, `conntrack`, активной ноды и замер реального пинга (РФ / Cloudflare / YouTube / OpenAI).
2. **Управление прокси (3 слота):**
   * Добавление/замена основной и дополнительных подписок (Мульти-Саб);
   * Просмотр пронумерованного списка, добавление и точечное удаление личных ключей (`vless`, `hy2`, `tuic`, `ss`, `wg`, `anytls`);
   * Генерация и перевыпуск бесплатного **Amnezia WARP 2.0 / WARP+**;
   * Переключатель режима **«Белые списки»** (показ/скрытие каскадных РФ-нод в подписке).
3. **Атомарное обновление ядер:** безопасное обновление `Sing-Box Extended`, `AdGuard Home` и веб-панели `Zashboard` с проверкой бинарников перед заменой.
4. **Пересборка конфига и сброс кэша:** актуализация правил и очистка таблицы `conntrack`.
5. **Живые логи Sing-Box:** быстрый просмотр системного журнала для диагностики.
6. **Мастер полной перенастройки:** повторный запуск инсталлятора с сохранением текущих параметров по `Enter`.
7. **Свои списки доменов:** добавление любых доменов (например, `+.example.com`) в принудительный прокси или в прямой обход (`DIRECT`) с автокомпиляцией в JSON Rule-Set v3.
8. **Маршрутизация устройств по IP:**
   * **Обход (`DIRECT`):** для рабочих ноутбуков или устройств, которые никогда не должны ходить через прокси;
   * **Full-VPN (`📺 Устройства`):** для Apple TV, Android TV, PlayStation, Xbox и Meta Quest.
9. **Сервисный режим, пароль и бэкап:** временная пауза проксирования в 1 клик, смена единого пароля (`Zashboard + AdGuard Home`) и полное резервное копирование в `/root/gateway_backup.tar.gz`.
10. **Автообновление (`04:00`) и Авто-Доктор (`Watchdog`):** управление фоновым обновлением ядер и самоисцелением служб по `cron`.
11. **Аппаратный Kill-Switch (`nftables`):** жесткая блокировка утечки трафика из LAN напрямую к роутеру провайдера в случае остановки `Sing-Box`.
12. **Сетевые настройки и Умный DHCP Sidecar:** безопасная смена IP шлюза/роутера и включение встроенного DHCP-сервера для роутеров с заблокированными настройками LAN.

