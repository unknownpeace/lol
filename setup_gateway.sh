## 🌐 Как подключить устройства в домашней сети к шлюзу

После установки шлюз доступен по выбранному вами IP-адресу (например, `192.168.1.2`), а ваш главный роутер остается на `192.168.1.1`. Выберите один из трех удобных способов:

### Способ А: На главном роутере (Рекомендуемый — для всего дома сразу)
Зайдите в настройки **DHCP (Локальная сеть)** вашего основного роутера и укажите IP шлюза (`192.168.1.2`) в двух полях:
* **Основной шлюз (Default Gateway / Опция 3):** `192.168.1.2`
* **DNS-сервер (DNS Server / Опция 6):** `192.168.1.2`

*(Переподключите устройства к Wi-Fi — весь дом сразу начнет работать через шлюз и без рекламы).*

### Способ Б: «Умный DHCP Sidecar» (Если у вас залоченный роутер Ростелеком / МТС / МГТС)
Если провайдерский роутер не дает поменять шлюз в настройках DHCP:
1. Откройте меню `gateway` -> пункт **12** -> выберите **«4) ВКЛЮЧИТЬ Умный DHCP-сервер на шлюзе»**.
2. В настройках роутера провайдера просто снимите галочку **«Включить DHCP-сервер»**.
Теперь сам шлюз будет раздавать IP-адреса (`.100–.239`) и автоматически назначать себя шлюзом и DNS-сервером.

### Способ В: Точечно на конкретном устройстве (ПК / Смартфон / Smart TV / Консоль)
В настройках сети устройства переключите IP с «Авто (DHCP)» на **«Вручную (Статический)»**:
* **IP-адрес:** любой свободный из вашей подсети (например, `192.168.1.50`)
* **Маска подсети:** `255.255.255.0` (или префикс `24`)
* **Шлюз (Маршрутизатор):** IP вашего шлюза (`192.168.1.2`)
* **DNS:** IP вашего шлюза (`192.168.1.2`)

