Полностью автоматизированный скрипт установки и управления **Sidecar-шлюзом (одноруким роутером / LXC-контейнером / мини-ПК)** для точечного обхода блокировок, замедлений ТСПУ и фильтрации рекламы во всей домашней сети без перепрошивки основного роутера.

Скрипт превращает любую **OpenWrt 25.x+** или **Alpine Linux 3.x** (Proxmox LXC / VM / Mini-PC / NanoPi / Raspberry Pi) в готовый шлюз уровня «поставил и забыл» со встроенным интерактивным меню `gateway`.

🔗 **Прямая ссылка на скрипт:** [`setup_gateway.sh`](https://raw.githubusercontent.com/unknownpeace/lol/refs/heads/main/setup_gateway.sh)

