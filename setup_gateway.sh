## 🖥 Веб-интерфейсы и CLI-команды

После установки вам доступны две веб-панели (с единым паролем, который вы задали при установке):

* 🎛 **Панель управления прокси (Zashboard):** `http://<IP_ШЛЮЗА>:9090/ui`
* 🛡 **Панель фильтрации рекламы (AdGuard Home):** `http://<IP_ШЛЮЗА>:3000`
* 🔌 **Локальный Mixed-прокси (HTTP / SOCKS5 для браузеров и приложений):** `<IP_ШЛЮЗА>:7890`

### Полезные команды терминала:
```sh
gateway             # Открыть интерактивное меню управления шлюзом
gateway status      # Запустить матрицу диагностики и замер задержек (Self-Test 2.0)
gateway install     # Запустить мастер первичной настройки заново
gateway autoupdate  # Принудительно запустить задачу обновления ядер и панелей
gateway watchdog    # Принудительно выполнить проверку здоровья служб
```

