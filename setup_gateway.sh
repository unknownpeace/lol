## ⚡ Быстрая установка (в одну строку)

Подключитесь к вашему устройству по SSH (`root`) и выполните одну из команд ниже. Скрипт автоматически очистит переносы строк, установит себя в систему как команду **`gateway`** и запустит мастер настройки.

### Вариант 1: Через `wget` (работает из коробки на чистой OpenWrt и Alpine)
```sh
wget -O /tmp/setup_gateway.sh "https://raw.githubusercontent.com/unknownpeace/lol/refs/heads/main/setup_gateway.sh" && sed -i 's/\r$//; 1s/^\xEF\xBB\xBF//' /tmp/setup_gateway.sh && chmod +x /tmp/setup_gateway.sh && sh /tmp/setup_gateway.sh
```

### Вариант 2: Через `curl` (с защитой от фрагментации TLS 1.3 Kyber на ТСПУ)
```sh
curl -fsSL --curves X25519:P-256 "https://raw.githubusercontent.com/unknownpeace/lol/refs/heads/main/setup_gateway.sh" -o /tmp/setup_gateway.sh && sed -i 's/\r$//; 1s/^\xEF\xBB\xBF//' /tmp/setup_gateway.sh && chmod +x /tmp/setup_gateway.sh && sh /tmp/setup_gateway.sh
```

### Вариант 3: Через зеркало GitHub (если провайдер блокирует `raw.githubusercontent.com`)
```sh
wget -O /tmp/setup_gateway.sh "https://ghproxy.net/https://raw.githubusercontent.com/unknownpeace/lol/refs/heads/main/setup_gateway.sh" && sed -i 's/\r$//; 1s/^\xEF\xBB\xBF//' /tmp/setup_gateway.sh && chmod +x /tmp/setup_gateway.sh && sh /tmp/setup_gateway.sh
